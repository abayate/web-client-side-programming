// Lab 5 - Task 3: speech (text-to-speech) modality.
// Based on the "speech" samples in https://github.com/openai/openai-node/tree/master/examples
// The response is a web Response object, so we pull an ArrayBuffer out of it and write an MP3.

import OpenAI from 'openai';
import dotenv from 'dotenv';
import fs from 'node:fs/promises';
import path from 'node:path';

dotenv.config({ override: true });

const openai = new OpenAI();

const OUTPUT_DIR = 'output';
const SCRIPT_TEXT =
  'Welcome to Lab Five. In this lab I built four things: a TensorFlow dot J S image ' +
  'classifier that runs entirely in the browser, a multi model comparison script, ' +
  'a LangChain guardian pipeline, and a retrieval augmented resume analyzer. ' +
  'This audio itself was generated by the OpenAI text to speech endpoint.';

// Each voice has a different character; generating two makes the difference audible.
const VOICES = ['nova', 'onyx'];

async function speak(voice) {
  console.log(`Synthesizing with voice "${voice}"...`);
  const started = Date.now();

  const response = await openai.audio.speech.create({
    model: 'gpt-4o-mini-tts',
    voice,
    input: SCRIPT_TEXT,
    instructions: 'Speak clearly and at a steady, confident pace, like a student presenting a lab demo.',
  });

  const buffer = Buffer.from(await response.arrayBuffer());
  const outPath = path.join(OUTPUT_DIR, `lab5-narration-${voice}.mp3`);
  await fs.writeFile(outPath, buffer);

  console.log(
    `  Saved ${outPath} (${(buffer.length / 1024).toFixed(1)} KB) in ${((Date.now() - started) / 1000).toFixed(1)}s`
  );
}

async function main() {
  await fs.mkdir(OUTPUT_DIR, { recursive: true });

  console.log('--- Text to Speech (gpt-4o-mini-tts) ---');
  console.log(`Script (${SCRIPT_TEXT.length} characters):\n${SCRIPT_TEXT}\n`);

  for (const voice of VOICES) {
    await speak(voice);
  }

  console.log('\nOpen the .mp3 files in the output/ folder to hear the result.');
}

main().catch((error) => {
  console.error('Speech generation failed:', error.message);
  process.exit(1);
});
